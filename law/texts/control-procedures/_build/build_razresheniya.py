def load_procedures(rel):
    page = (ROOT / rel).read_bytes().decode("utf-8-sig", errors="replace")
    rows = {}
    for cells in table_cells(page):
        if len(cells) != 5:
            continue
        match = re.match(rf"(\d+(?:\.\d+[{SUPERSCRIPT}]*)+)\.\s+(.*)", cells[0][0])
        if match:
            rows[match.group(1)] = {
                "name": match.group(2), "regulator": cells[1][0], "authority": cells[2][0], "term": cells[3][2],
                "clean": all(cell[0] == cell[1] for cell in cells[:4]),
                "all": [cell[0] for cell in cells],
            }
    return rows


