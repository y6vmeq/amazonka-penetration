def mark_to_ellipsis(text):
    """Заменяет знак сноски (звёздочки) внутри абзаца многоточием: проверка цитат сверяет части по отдельности."""
    return re.sub(r"\*+", "…", text)


def strip_leading_marks(text):
    return re.sub(r"^\*+\s*", "", text.strip())


def run_check():
    result = subprocess.run(
        [sys.executable, "-I", "-X", "utf8", "tools/md_quotes_check.py", TARGET, *CHECK_FILES],
        cwd=ROOT, capture_output=True, text=True, encoding="utf-8", timeout=600,
    )
    lines = result.stdout.splitlines()
    summary = lines[0].split(": ", 1)[1] if lines else "проверка не запустилась"
    return summary, lines[1:]


