def article(number):
    starts = [i for i, line in enumerate(lines) if line.startswith(f"Статья {number}. ")]
    if not starts:
        raise SystemExit(f"не найдена статья {number}")
    body = [lines[starts[-1]]]
    for line in lines[starts[-1] + 1:]:
        if line.startswith(("Статья ", "ГЛАВА ")):
            break
        body.append(line)
    return body


