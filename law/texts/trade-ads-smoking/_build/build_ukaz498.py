def para(start, count=1):
    i = next((n for n, line in enumerate(lines) if line.startswith(start)), None)
    if i is None:
        raise SystemExit(f"не найден абзац: {start[:60]}")
    return "«" + "\n".join(lines[i:i + count]) + "»"


def cell_text(raw):
    raw = re.sub(r"(?i)<br\s*/?>|</p>", " ¶ ", raw)
    raw = html.unescape(re.sub(r"<[^>]*>", " ", raw)).replace("\xa0", " ")
    raw = re.sub(r"\s+", " ", raw).strip()
    raw = re.sub(r"^(?:¶ ?)+|(?: ?¶)+$", "", raw).strip()
    return re.sub(r"\s*¶\s*", "; ", raw).replace(":;", ":")


