def article(number, source=None):
    source = lines if source is None else source
    starts = [i for i, line in enumerate(source) if line.startswith(f"Статья {number}. ")]
    body = [source[starts[-1]]]
    for line in source[starts[-1] + 1:]:
        if line.startswith(("Статья ", "ГЛАВА ")):
            break
        body.append(line)
    return body


def para(body, start, count=1):
    """Абзац, который начинается с start, и следующие за ним (count штук подряд)."""
