def find(suffix):
    return sorted(RAW.glob("*" + suffix))[0]


def item(path):
    """Строка манифеста для PDF, из которого извлечён текст."""
    pdf = path.with_suffix(".pdf").name
    return next(m for m in MANIFEST if m.get("file", "").endswith(pdf))


def clean(path):
    text = path.read_text(encoding="utf-8")
    text = PAGE_BREAK.sub(" ", text)
    text = re.sub(r"(?<=\w)-\s*\n\s*(?=\w)", "-", text)
    return re.sub(r"\s+", " ", text).strip()


def between(text, start, end):
    a = text.find(start)
    if a < 0:
        raise SystemExit(f"не найдено начало: {start[:60]}")
    b = text.find(end, a)
    if b < 0:
        raise SystemExit(f"не найден конец: {end[:60]}")
    return "«" + text[a:b + len(end)] + "»"


def source_line(path, what):
    m = item(path)
    return (f"  - {what}: `{REL}/{m['file'].split('/')[-1]}`, SHA-256 `{m['sha256']}`, "
            f"загружено {m['fetched_at'][:16].replace('T', ' ')} UTC, адрес {m['url']};")


