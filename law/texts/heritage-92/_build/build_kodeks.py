def paragraphs(path):
    """Абзацы страницы без разметки: один абзац — одна строка."""
    text = path.read_bytes().decode("utf-8-sig")
    text = re.sub(r"(?is)<(script|style)\b.*?</\1>", " ", text)
    text = re.sub(r"(?i)<br\s*/?>|</p>|</div>|</tr>|</h\d>|</li>", "\n", text)
    text = html.unescape(re.sub(r"<[^>]*>", "", text)).replace("\xa0", " ")
    lines = [re.sub(r"[ \t]+", " ", line).strip() for line in text.splitlines()]
    return [line for line in lines if line]


def article(lines, number):
    """Абзацы статьи; берётся второе вхождение заголовка (первое — в оглавлении)."""
    starts = [i for i, line in enumerate(lines) if line.startswith(f"Артыкул {number}. ")]
    body = [lines[starts[1]]]
    for line in lines[starts[1] + 1:]:
        if line.startswith(("Артыкул ", "ГЛАВА ", "РАЗДЗЕЛ ")):
            break
        body.append(line)
    return body


def points(body, wanted):
    """Пункты статьи с номерами из wanted: строка «N. …» и всё до следующего пункта."""
    out, keep = [], False
    for line in body[1:]:
        match = re.match(r"^(\d+)\. ", line)
        if match:
            keep = int(match.group(1)) in wanted
        if keep:
            out.append(line)
    return out


def first(body, number, count=1):
    """Первые count абзацев пункта number."""
    return points(body, {number})[:count]


def quote(lines):
    return "«" + "\n".join(lines) + "»"


def procedure(lines, code):
    """Строка административной процедуры: наименование, орган-регулятор, уполномоченный орган."""
    index = next(i for i, line in enumerate(lines) if line.startswith(code + " "))
    return lines[index], lines[index + 1], lines[index + 2]


