def article(number):
    """Абзацы статьи КоАП. Берётся последнее вхождение заголовка: первое стоит в оглавлении."""
    starts = [i for i, line in enumerate(koap) if line.startswith(f"Статья {number}. ")]
    body = [koap[starts[-1]]]
    for line in koap[starts[-1] + 1:]:
        if line.startswith(("Статья ", "ГЛАВА ")):
            break
        body.append(line)
    return body


def parts(body, wanted):
    """Части статьи с номерами из wanted вместе с санкцией (абзац после части)."""
    out, keep = [], False
    for line in body[1:]:
        match = re.match(r"^(\d+)\. ", line)
        if match:
            keep = int(match.group(1)) in wanted
        elif line.startswith("Примечани"):
            keep = False
        if keep:
            out.append(line)
    return out


def quote(lines):
    return "«" + "\n".join(lines) + "»"


def protocol(start):
    """Абзац статьи 3.30 ПИКоАП, который начинается с start (последнее вхождение)."""
    found = [line for line in pikoap if line.startswith(start)]
    if not found:
        raise SystemExit(f"не найден абзац ПИКоАП: {start}")
    return found[-1]


def fragment(line, start, end):
    a = line.index(start)
    b = line.index(end, a) + len(end)
    return line[a:b]


def edition(lines):
    return next(line for line in lines if line.startswith("с изменениями (дополнениями), внесенными"))


