def main():
    path = HERE / "photos.jsonl"
    lines = [line for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]
    have = {json.loads(line)["id"] for line in lines}
    added = 0
    with path.open("a", encoding="utf-8", newline="\n") as out:
        for (pid, record, author, number, total, photo_id, published, shot, shot_file, zone, text, seats, animals) in ROWS:
            if pid in have:
                continue
            out.write(json.dumps({
                "id": pid, "venue": "amazonka-mogilev", "source": SOURCE, "review_record": record,
                "review_author": author, "position": f"{number} из {total}", "kind": "photo",
                "photo_id": photo_id, "attribution": author, "published": published, "shot_date": shot,
                "link": None, "screenshot": "screenshots/" + shot_file, "captured_at": "2026-11-15",
                "zone": zone, "description": text, "tables_seats": seats, "animals": animals,
            }, ensure_ascii=False) + "\n")
            added += 1
    print(f"added={added} total={len(lines) + added}")


if __name__ == "__main__":
    main()
